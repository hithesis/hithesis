#!/usr/bin/env python3
"""Generate continuation captions from actual Word pagination (source -> generated DOCX/PDF)."""
import argparse
from copy import deepcopy
import importlib.util
import json
from pathlib import Path
import re
import shutil
import xml.etree.ElementTree as ET
import zipfile

ROOT=Path(__file__).resolve().parents[1]
def load(name,path):
    spec=importlib.util.spec_from_file_location(name,path)
    m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);return m
xml=load('continuation_table_xml',ROOT/'scripts/word-auto-table.py')
w=xml.w;NS=w.NS|{'wp':'http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing'}
W=xml.W
SRC_TABLE='HITAutoSourceTableCaption'
GEN_TABLE='HITAutoGeneratedTableCaption'
FIG_START='HITAutoFigureStart'
FIG_END='HITAutoFigureEnd'
FIG_CAP='HITAutoFigureCaptionTemplate'
FIG_EN='HITAutoFigureEnglishTemplate'
ROLE='HITAutoContinuationRole'


def read_package(path):
    with zipfile.ZipFile(path) as z:return {n:z.read(n) for n in z.namelist()}


def write_package(path,payload):
    with zipfile.ZipFile(path,'x',zipfile.ZIP_DEFLATED) as z:
        for name,data in payload.items():
            info=zipfile.ZipInfo(name,(1980,1,1,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED
            z.writestr(info,data)


def style(p):
    node=p.find('w:pPr/w:pStyle',NS)
    return node.get(W+'val') if node is not None else ''


def set_style(p,name):
    pr=xml.properties(p,'pPr')
    for n in list(pr):
        if n.tag==W+'pStyle':pr.remove(n)
    pr.insert(0,w.element('pStyle',val=name))


def keep(p,value):
    pr=xml.properties(p,'pPr')
    for n in list(pr):
        if n.tag==W+'keepNext':pr.remove(n)
    pr.insert(1 if pr.find('w:pStyle',NS) is not None else 0,w.element('keepNext',val=int(value)))


def clean_flow(p,caption=False):
    xml.flow_paragraph(p)
    pr=p.find('w:pPr',NS);spacing=pr.find('w:spacing',NS)
    if spacing is not None:
        spacing.set(W+'before','60' if caption else '0');spacing.set(W+'after','0')
        for k in ('beforeLines','afterLines'):spacing.attrib.pop(W+k,None)
    for n in list(pr):
        if n.tag==W+'pageBreakBefore':pr.remove(n)


def marker(text,name):
    p=w.body_paragraph(text,english=True,blank=True)
    set_style(p,name)
    for pr in [p.find('w:pPr/w:rPr',NS),*p.findall('w:r/w:rPr',NS)]:
        if pr is not None:
            for n in pr.findall('w:sz',NS):n.set(W+'val','18')
            pr.append(w.element('color',val='666666'))
    return p


def role(payload):
    settings=ET.fromstring(payload['word/settings.xml'])
    entry=settings.find(f'w:docVars/w:docVar[@w:name="{ROLE}"]',NS)
    return entry.get(W+'val') if entry is not None else None


def set_role(payload,value):
    original=payload['word/settings.xml'];root=ET.fromstring(original)
    variables=root.find('w:docVars',NS)
    if variables is None:
        variables=w.element('docVars');compat=root.find('w:compat',NS)
        root.insert(list(root).index(compat)+1 if compat is not None else len(root),variables)
    entry=variables.find(f'w:docVar[@w:name="{ROLE}"]',NS)
    if entry is None:entry=w.element('docVar',name=ROLE);variables.append(entry)
    entry.set(W+'val',value);payload['word/settings.xml']=w.serialize(root,original)


def ensure_styles(payload):
    original=payload['word/styles.xml'];root=ET.fromstring(original)
    for name in (SRC_TABLE,GEN_TABLE,FIG_START,FIG_END,FIG_CAP,FIG_EN):
        if root.find(f'w:style[@w:styleId="{name}"]',NS) is None:
            node=w.element('style',type='paragraph',styleId=name)
            node.extend([w.element('name',val=name),w.element('basedOn',val='a')]);root.append(node)
    payload['word/styles.xml']=w.serialize(root,original)


class Identity:
    def __init__(self,root):
        self.book=max((int(n.get(W+'id')) for n in root.findall('.//w:bookmarkStart',NS)),default=0)+1
        self.drawing=max((int(n.get('id')) for n in root.findall('.//wp:docPr',NS)),default=10000)+1
        self.names={n.get(W+'name') for n in root.findall('.//w:bookmarkStart',NS)}
        self.shape=0
    def bookmark(self,nodes,name):
        if name in self.names:raise ValueError('Generated bookmark name collides with source: '+name)
        ps=[p for node in nodes for p in node.iter(W+'p')]
        if not ps:raise ValueError('A registered block has no paragraphs')
        first,last=ps[0],ps[-1]
        first.insert(1 if first.find('w:pPr',NS) is not None else 0,w.element('bookmarkStart',id=self.book,name=name))
        last.append(w.element('bookmarkEnd',id=self.book));self.book+=1;self.names.add(name)
        return name
    def cloned(self,node):
        node=deepcopy(node);shapes={}
        for parent in node.iter():
            for n in list(parent):
                if n.tag in (W+'bookmarkStart',W+'bookmarkEnd'):parent.remove(n)
            for attr in list(parent.attrib):
                if attr.endswith('}paraId') or attr.endswith('}textId'):parent.attrib.pop(attr)
            local=parent.tag.rsplit('}',1)[-1]
            if local in ('docPr','cNvPr') and parent.get('id') is not None:
                parent.set('id',str(self.drawing));self.drawing+=1
            if local=='shape' and parent.get('id'):
                old=parent.get('id');self.shape+=1;new=f'HITAutoShape{self.shape}'
                shapes[old]=new;parent.set('id',new)
        for n in node.iter():
            if n.get('ShapeID') in shapes:n.set('ShapeID',shapes[n.get('ShapeID')])
            if n.tag.rsplit('}',1)[-1]=='OLEObject' and n.get('ObjectID'):
                n.set('ObjectID','_HITAuto'+str(self.shape)+'_'+str(self.drawing));self.drawing+=1
        return node


def caption_text(node):
    return ''.join((n.text or '') if n.tag==W+'t' else (' ' if n.tag in (W+'tab',W+'br',W+'cr') else '') for n in node.iter())


def caption_label(text,kind):
    # Preserve the separator before titles such as "1号试样"; compacting the
    # complete line would incorrectly turn table 6-1 into table 6-11.
    match=re.match(re.escape(kind)+r'\s*\d+(?:\s*[-－]\s*\d+)*',text.replace('\u200b','').strip())
    if not match:raise ValueError('Cannot identify a plain-text caption label: '+text)
    return re.sub(r'\s+','',match.group())


def models(root):
    body=root.find('w:body',NS);children=list(body);tables=[];figures=[]
    for i,node in enumerate(children):
        if node.tag==W+'tbl':
            rows=node.findall('w:tr',NS)
            p=rows[0].find('w:tc/w:p',NS) if rows else None
            if p is not None and style(p)==SRC_TABLE:
                if len(rows)<3 or not all(r.find('w:trPr/w:tblHeader',NS) is not None for r in rows[:2]):
                    raise ValueError('Registered table needs two header rows and at least one data row')
                tables.append({'start':i,'end':i+1,'node':node,'rows':rows[2:],'label':caption_label(caption_text(p),'表')})
    i=0
    while i<len(children):
        if style(children[i])!=FIG_START:i+=1;continue
        start=i;end=next((j for j in range(i+1,len(children)) if style(children[j])==FIG_END),None)
        if end is None:raise ValueError('Figure group has no end marker')
        region=children[start+1:end]
        cap_at=next((j for j,n in enumerate(region) if style(n)==FIG_CAP),None)
        if cap_at is None:raise ValueError('Figure group has no normal-caption template')
        caps=[region[cap_at]];after=cap_at+1
        if after<len(region) and style(region[after])==FIG_EN:caps.append(region[after]);after+=1
        content=region[:cap_at]
        # Word may save older compatibility-mode inline pictures as VML.
        starts=[j for j,n in enumerate(content) if n.find('.//w:drawing',NS) is not None or n.find('.//w:pict',NS) is not None]
        units=[content[j:(starts[k+1] if k+1<len(starts) else len(content))] for k,j in enumerate(starts)]
        if any(n.tag!=W+'p' for unit in units for n in unit):raise ValueError('Figure blocks currently support inline picture paragraphs and labels')
        prefix=content[:starts[0]] if starts else content
        figures.append({'start':start,'end':end+1,'units':units,'captions':caps,'prefix':prefix,'suffix':region[after:],
                        'label':caption_label(caption_text(caps[0]),'图')})
        i=end+1
    return tables,figures


def prepare(source,destination):
    if destination.exists():raise FileExistsError(str(destination))
    payload=read_package(source)
    if role(payload):raise ValueError('Use an unregistered automatic-table copy for prepare; update a source file directly')
    original=payload['word/document.xml'];root=ET.fromstring(original);before=deepcopy(root)
    body=root.find('w:body',NS);children=list(body);registered=0
    for table in body.findall('w:tbl',NS):
        rows=table.findall('w:tr',NS)
        if len(rows)>2 and rows[0].find('w:trPr/w:tblHeader',NS) is not None:
            p=rows[0].find('w:tc/w:p',NS)
            if p is not None and re.match(r'^表\d',w.compact(w.text(p))):
                set_style(p,SRC_TABLE);registered+=1
    def image_index(identifier):
        return next((i for i,p in enumerate(children) if any(n.get('id')==str(identifier) for n in p.findall('.//wp:docPr',NS))),None)
    first,second=image_index(7120),image_index(7130)
    if (first is None)!=(second is None):raise ValueError('Incomplete known figure-block pair')
    if first is not None:
        finish=next(i for i in range(second+1,len(children)) if w.compact(w.text(children[i]))=='图1-1（续图）')
        zh=next(p for p in children[:first] if w.compact(w.text(p))=='图1-1气体润滑轴承的分类')
        en=next((p for p in children[:first] if w.text(p).startswith('Fig. 1-1')),None)
        units=[[deepcopy(children[first]),deepcopy(children[first+1])],[deepcopy(children[second]),deepcopy(children[second+1])]]
        for unit in units:
            for p in unit:clean_flow(p)
            keep(unit[0],True);keep(unit[-1],False)
        captions=[deepcopy(zh)]
        if en is not None:captions.append(deepcopy(en))
        for j,p in enumerate(captions):
            clean_flow(p,caption=j==0);set_style(p,FIG_CAP if j==0 else FIG_EN);keep(p,j<len(captions)-1)
        nodes=[marker('【自动续图图组开始：编辑/复制图片行与子图说明，图题由更新命令生成】',FIG_START),
               *units[0],*units[1],*captions,marker('【自动续图图组结束】',FIG_END)]
        for n in children[first:finish+1]:
            if n.find('w:pPr/w:sectPr',NS) is not None:raise ValueError('Figure registration would remove a section boundary')
            body.remove(n)
        at=list(body).index(children[first-1])+1
        keep(children[first-1],False)
        for offset,n in enumerate(nodes):body.insert(at+offset,n)
        xml.restore_bookmarks(root,before,captions[0]);registered+=1
    if not registered:raise ValueError('No supported automatic table or known figure group was found')
    ensure_styles(payload);set_role(payload,'source')
    payload['word/document.xml']=w.serialize(root,original)
    destination.parent.mkdir(parents=True,exist_ok=True);write_package(destination,payload)
    return {'source':str(source.resolve()),'source_sha256':w.digest(source),'registered_sha256':w.digest(destination),
            'registered_groups':registered}


def page_break():
    p=w.body_paragraph('',english=True,blank=True);pr=p.find('w:pPr',NS)
    for n in list(pr):
        if n.tag==W+'spacing':n.set(W+'line','20');n.set(W+'lineRule','exact')
    pr.insert(0,w.element('pageBreakBefore'))
    for n in pr.findall('w:rPr/w:sz',NS):n.set(W+'val','2')
    keep(p,False);return p


def render(payload,plan):
    original=payload['word/document.xml'];root=ET.fromstring(original)
    original_marks={n.get(W+'id'):n.get(W+'name') for n in root.findall('.//w:bookmarkStart',NS)}
    tables,figures=models(root);ids=Identity(root);changes=[];spec={'tables':[],'figures':[]}
    for ti,table in enumerate(tables):
        count=len(table['rows']);sizes=plan.get('tables',{}).get(str(ti),[count])
        if sum(sizes)!=count or any(n<=0 for n in sizes):raise ValueError('Invalid table partition')
        nodes=[];offset=0
        for fi,size in enumerate(sizes):
            part=deepcopy(table['node'])
            for n in list(part):
                if n.tag==W+'tr':part.remove(n)
            source_headers=table['node'].findall('w:tr',NS)[:2]
            headers=[deepcopy(n) if fi==0 else ids.cloned(n) for n in source_headers]
            for header in headers:
                for paragraph in header.findall('w:tc/w:p',NS):keep(paragraph,True)
            cap=headers[0].find('w:tc/w:p',NS);set_style(cap,GEN_TABLE)
            if fi:w.replace_text(cap,table['label']+'（续表）')
            part.extend([*headers,*[deepcopy(n) for n in table['rows'][offset:offset+size]]])
            name=ids.bookmark([cap],f'HITAC_T{ti}F{fi}')
            if fi:nodes.append(page_break())
            nodes.append(part)
            spec['tables'].append({'id':f'T{ti}F{fi}','group':ti,'fragment':fi,'offset':offset,'data_rows':size,'bookmark':name})
            offset+=size
        changes.append((table['start'],table['end'],nodes))
    for gi,figure in enumerate(figures):
        groups=plan.get('figures',{}).get(str(gi),[[i] for i in range(len(figure['units']))])
        if [i for group in groups for i in group]!=list(range(len(figure['units']))):raise ValueError('Invalid figure partition')
        nodes=[deepcopy(n) for n in figure['prefix']];entry={'id':gi,'units':[],'captions':[],'groups':groups}
        forced=str(gi) in plan.get('figures',{})
        for ci,group in enumerate(groups):
            if forced and ci:nodes.append(page_break())
            for unit_index in group:
                unit=[deepcopy(n) for n in figure['units'][unit_index]]
                for p in unit:keep(p,True)
                entry['units'].append(ids.bookmark(unit,f'HITAC_F{gi}U{unit_index}'));nodes.extend(unit)
            captions=[deepcopy(n) if ci==0 else ids.cloned(n) for n in figure['captions'][:1 if ci else None]]
            if ci:w.replace_text(captions[0],figure['label']+'（续图）')
            for j,p in enumerate(captions):
                set_style(p,GEN_TABLE);keep(p,j<len(captions)-1)
            entry['captions'].append(ids.bookmark(captions,f'HITAC_F{gi}C{ci}'));nodes.extend(captions)
        nodes.extend(deepcopy(n) for n in figure['suffix'])
        spec['figures'].append(entry);changes.append((figure['start'],figure['end'],nodes))
    body=root.find('w:body',NS);children=list(body)
    for start,end,nodes in sorted(changes,reverse=True,key=lambda c:c[0]):
        for n in children[start:end]:body.remove(n)
        for offset,n in enumerate(nodes):body.insert(start+offset,n)
    final_marks=root.findall('.//w:bookmarkStart',NS)
    ids_now=[n.get(W+'id') for n in final_marks]
    if len(ids_now)!=len(set(ids_now)):raise ValueError('Rendering duplicated bookmark IDs')
    remaining={n.get(W+'id'):n.get(W+'name') for n in final_marks}
    if not original_marks.items()<=remaining.items():raise ValueError('Rendering would remove source bookmark identities')
    if set(ids_now)!={n.get(W+'id') for n in root.findall('.//w:bookmarkEnd',NS)}:
        raise ValueError('Rendering produced unbalanced bookmarks')
    result=payload.copy();set_role(result,'generated')
    result['word/document.xml']=w.serialize(root,original)
    return result,spec


def split_sizes(rows):
    groups=[]
    for row in rows:
        if row['start_page']!=row['end_page']:raise ValueError('A single data row split across pages')
        page=row['start_page']
        if not groups or groups[-1][0]!=page:groups.append([page,0])
        groups[-1][1]+=1
    return [n for page,n in groups]


def next_plan(layout,spec,old):
    plan={'tables':{},'figures':{}}
    for measured in layout['tables']:
        requested=next(t for t in spec['tables'] if t['id']==measured['id'])
        if len(measured['rows'])<3:raise ValueError('A table fragment has no data rows')
        first_page=measured['rows'][2]['start_page']
        if any(r['start_page']!=first_page or r['end_page']!=first_page for r in measured['rows'][:2]):
            raise ValueError('Table caption/header separated from the first data row')
        sizes=split_sizes(measured['rows'][2:])
        plan['tables'].setdefault(str(requested['group']),[]).extend(sizes)
    for measured in layout['figures']:
        entry=next(f for f in spec['figures'] if f['id']==measured['id'])
        key=str(entry['id']);units=measured['units']
        if key not in old.get('figures',{}):
            groups=[]
            for i,unit in enumerate(units):
                if unit.get('inline_shapes',0)<1:raise ValueError('Registered figure blocks must contain inline pictures')
                if unit['start_page']!=unit['end_page']:raise ValueError('Figure block exceeds a page; split the artwork into blocks first')
                if not groups or units[groups[-1][0]]['start_page']!=unit['start_page']:groups.append([])
                groups[-1].append(i)
        else:
            groups=[]
            for ci,group in enumerate(entry['groups']):
                cap=measured['captions'][ci]
                if cap['start_page']!=cap['end_page']:raise ValueError('Figure caption split across pages')
                if units[group[-1]]['end_page']!=cap['start_page']:
                    raise ValueError('A picture block and its caption cannot fit together')
                current=[]
                for i in group:
                    if units[i]['start_page']!=units[i]['end_page']:raise ValueError('Picture block split across pages')
                    if current and units[current[0]]['start_page']!=units[i]['start_page']:groups.append(current);current=[]
                    current.append(i)
                if current:groups.append(current)
        plan['figures'][key]=groups
    return plan


def layout_signature(layout):
    return {'pages':layout['pages'],'tables':layout['tables'],'figures':layout['figures']}


def update(source,out,vm='Windows',host='10.211.55.2'):
    if out.exists():raise FileExistsError(str(out))
    source_hash=w.digest(source)
    payload=read_package(source)
    if role(payload)!='source':raise ValueError('Update requires the editable source DOCX, not a generated output')
    root=ET.fromstring(payload['word/document.xml']);tables,figures=models(root)
    if not tables and not figures:raise ValueError('No registered groups remain')
    out.mkdir(parents=True);measurer=load('word_continuation_measurer',ROOT/'scripts/word-layout-vm.py')
    plan={};previous=None;history=[]
    for iteration in range(10):
        work=out/f'iteration-{iteration:02}';work.mkdir()
        rendered,spec=render(payload,plan);path=work/'input.docx';write_package(path,rendered)
        (work/'plan.json').write_text(json.dumps(plan,ensure_ascii=False,indent=2)+'\n')
        layout=measurer.measure(path,work/'word',spec,vm,host)
        if w.digest(source)!=source_hash:
            raise RuntimeError('Source changed during update; save it and rerun into a new output directory')
        proposed=next_plan(layout,spec,plan)
        history.append({'iteration':iteration,'input_sha256':w.digest(path),'pages':layout['pages'],'plan':plan,'next_plan':proposed})
        signature=layout_signature(layout)
        if proposed==plan and previous==signature:
            shutil.copy2(path,out/'output.docx');shutil.copy2(work/'word/output.pdf',out/'output.pdf')
            result={'kind':'word-pagination-derived-continuation-captions','source':str(source.resolve()),'source_sha256':source_hash,
                    'output_docx_sha256':w.digest(out/'output.docx'),'output_pdf_sha256':w.digest(out/'output.pdf'),
                    'generator_sha256':w.digest(__file__),'word_version':layout['word_version'],'compatibility_mode':layout['compatibility_mode'],
                    'final_plan':plan,'layout':layout,'measurement_spec':spec,'iterations':history,
                    'workflow':'edit source DOCX and rerun update; generated output is derived, not live while typing'}
            (out/'result.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
            print('UPDATED',out,'pages',layout['pages'],'iterations',iteration+1,flush=True)
            return result
        previous=signature if proposed==plan else None
        plan=proposed
    raise RuntimeError('Word layout did not converge; iteration evidence retained')


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('action',choices=('prepare','update'))
    p.add_argument('--input',type=Path,required=True);p.add_argument('--output',type=Path,required=True)
    p.add_argument('--vm',default='Windows');p.add_argument('--host',default='10.211.55.2')
    args=p.parse_args()
    if args.action=='prepare':print(json.dumps(prepare(args.input,args.output),ensure_ascii=False))
    else:update(args.input,args.output,args.vm,args.host)


if __name__=='__main__':main()
