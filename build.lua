--[[
  build.lua -- l3build configuration for hithesis

  Harbin Institute of Technology Thesis Template

  Targets
    l3build unpack          unpack hithesis.dtx into build/unpacked
    l3build doc             typeset hithesis.pdf (XeLaTeX, CJK)
    l3build install         install runtime files into TEXMFHOME
    l3build install --full  also install documentation and sources
    l3build ctan            build the CTAN archive (hithesis-ctan.zip)
    l3build upload          validate / upload the archive to CTAN
    l3build tag <ver>       bump the version + date in hithesis.dtx
    l3build clean           remove the build directory
]]

-- Package identity
module = "hithesis"

-- The documentation loads CJK fonts, so it must be typeset with XeLaTeX
typesetexe  = "xelatex"
typesetopts = "-interaction=nonstopmode"

-- Runtime files extracted by hithesis.ins and installed into tex/latex/hithesis/
-- (.sty covers dtx-style.sty, which is only needed while typesetting the docs)
installfiles = {"*.cls", "*.sty", "*.cfg", "*.eps"}

-- BibTeX styles -> bibtex/bst/hithesis/, MakeIndex styles -> makeindex/hithesis/
bstfiles       = {"*.bst"}
makeindexfiles = {"*.ist"}

-- dtx-style.sty is a documentation-only style: keep it out of the installed
-- runtime tree. It is still available to `l3build doc` via the local build tree.
excludefiles = {"*~", "build.lua", "config-*.lua", "dtx-style.sty"}

-- Sources shipped on CTAN (placed in source/latex/hithesis/)
sourcefiles = {"hithesis.dtx", "hithesis.ins"}

-- Text documentation shipped on CTAN (placed in doc/latex/hithesis/)
textfiles  = {"README.md"}
ctanreadme = "README.md"

-- Treat the vector graphics as binary when creating archives
binaryfiles = {"*.eps"}

-- Also ship a ready-made TDS archive (hithesis.tds.zip) inside the CTAN archive
packtdszip = true

-- Only these graphics are used by the document classes at runtime; the rest
-- are documentation/demo figures that belong in the doc tree.
tdslocations = {
  "doc/latex/hithesis/hithesis-golfer.eps",
  "doc/latex/hithesis/hithesis-zfb.eps",
}

-- Ship the example templates inside the TDS doc tree, so the tds.zip is
-- self-contained and the installer never has to run hithesis.ins (which writes
-- into examples/... subdirectories that LaTeX cannot create on the fly).
-- `l3build ctan` therefore expects `make cls` to have populated examples/ with
-- the generated class files first (the CI workflow does this).
tdsdirs = {
  ["examples"] = "doc/latex/hithesis/examples",
}

-- ---------------------------------------------------------------------------
-- Documentation typesetting
--
-- The .dtx displays the example templates with
--   \lstinputlisting{examples/hitbook/.../thesis.tex}
-- so the example tree must be present in the typeset directory. l3build's own
-- file copy flattens subdirectories, hence this hook copies the tree verbatim.
-- ---------------------------------------------------------------------------
function docinit_hook()
  return cp("examples", sourcefiledir, typesetdir)
end

-- ---------------------------------------------------------------------------
-- Version tagging
--
--   l3build tag v3.2.1 --date 2026-10-08
--
-- updates the two \Provides... lines in hithesis.dtx. The version is stored
-- once without the leading "v" (the .dtx driver line) and once with it (the
-- shared guard line used by the generated .cls/.cfg files).
-- ---------------------------------------------------------------------------
function update_tag(file, content, tagname, tagdate)
  if file ~= "hithesis.dtx" then
    return content
  end
  local version = (tagname or ""):gsub("^v", "")            -- v3.2.1 -> 3.2.1
  local date    = (tagdate or os.date("%Y-%m-%d")):gsub("%-", "/")

  -- \ProvidesFile{hithesis.dtx}[0000/00/00 3.1e Harbin Institute ...]
  content = content:gsub(
    "\\ProvidesFile{hithesis%.dtx}%[([^%]]*)%]",
    function(inner)
      local _, _, desc = (inner or ""):match("^(%S+)%s+(%S+)%s+(.*)$")
      desc = desc or "Harbin Institute of Technology Thesis Template"
      return "\\ProvidesFile{hithesis.dtx}[" .. date .. " " .. version
        .. " " .. desc .. "]"
    end
  )

  -- %<...>[0000/00/00 v3.1e Harbin Institute of Technology Thesis Template]
  content = content:gsub(
    "(%[)[^%]]* v[^ ]+ (Harbin Institute of Technology Thesis Template%])",
    "%1" .. date .. " v" .. version .. " %2"
  )
  return content
end

function tag_hook(tagname, tagdate)
  print("hithesis set to " .. (tagname or "?") .. " (" .. (tagdate or "?") .. ")")
  return 0
end

-- ---------------------------------------------------------------------------
-- CTAN upload metadata
--
--   l3build ctan                     # build hithesis-ctan.zip
--   l3build upload --dry-run         # validate the archive only
--   l3build upload v3.2.1            # validate, then ask before uploading
--   l3build upload v3.2.1 \
--     --message "..." --email you@example.com
--
-- The announcement defaults to RELEASE_NOTES.md (generated by `make changes`)
-- and can be overridden with --message or --file.
--
-- By default `l3build upload` asks for confirmation before posting to CTAN.
-- Set the CTAN_UPLOAD environment variable to "true" to upload non-interactively
-- (used by the GitHub Actions workflow on a version bump). Locally the prompt
-- is kept unless this variable is set.
-- ---------------------------------------------------------------------------
if os.getenv("CTAN_UPLOAD") == "true" then
  ctanupload = true
end

local function dtx_version()
  local f = assert(io.open("hithesis.dtx", "r"))
  local content = f:read("*a")
  f:close()
  local inner = content:match("\\ProvidesFile{hithesis%.dtx}%[([^%]]*)%]")
  local _, version = (inner or ""):match("^(%S+)%s+(%S+)")
  return version or "0.0.0"
end

